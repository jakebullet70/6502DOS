"""Generate the API files from tools/api.py.

    python tools/genapi.py

Writes build/gen/api.inc (the version, the call numbers and entries, the error numbers and the
find buffer offsets), build/gen/api.s (the routine table, api_bad and the error messages) and
docs/API.md. A reserved number gets an entry that runs api_bad. tools/build.py runs it before it assembles. Exit status 1 when api.py is
inconsistent.

It also writes the API_ entry CONSTs into lib/DOS.UXI, between the lines UXI_BEGIN and UXI_END.
It writes DOS.UXI only when that block changes, since tools/uxb.py recompiles every program that
includes a newer DOS.UXI.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import api  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "build", "gen")
HEADER = "Generated by tools/genapi.py from tools/api.py. Do not edit."
DOS_UXI = os.path.join(ROOT, "lib", "DOS.UXI")
UXI_BEGIN = "  ' ---- the call entries: generated by tools/genapi.py from tools/api.py, do not edit ----"
UXI_END = "  ' ---- end of the call entries ----"
UXI_WIDTH = 100


def check():
    """Return a list of the faults in api.py."""
    faults = []
    numbers = [c["number"] for c in api.CALLS]
    if sorted(numbers + list(api.RESERVED)) != list(range(count())) or numbers != sorted(numbers):
        faults.append("call numbers and RESERVED must run 0, 1, 2, ..., the calls in order")
    names = [c["name"] for c in api.CALLS]
    for name in set(names):
        if names.count(name) > 1:
            faults.append("call %s is listed twice" % name)
    known = {e[0] for e in api.ERRORS}
    if len(known) != len(api.ERRORS):
        faults.append("an error number is listed twice")
    for c in api.CALLS:
        for number in c["errors"]:
            if number not in known:
                faults.append("call %s returns error %d, which ERRORS lacks" % (c["name"], number))
    for number, name, message in api.ERRORS:
        if not 0 < number < 256 or len(message) > 255:
            faults.append("error %d does not fit in a byte" % number)
    if api.GATE_ENTRIES + 3 * count() > 0x400:
        faults.append("the call entries run past $03FF")
    offset = 0
    for start, size, name, field in api.FIND_BUFFER:
        if start != offset:
            faults.append("find buffer field %s starts at %d, not %d" % (field, start, offset))
        offset = start + size
    return faults


def count():
    """The number of call entries: the calls and the reserved numbers."""
    return len(api.CALLS) + len(api.RESERVED)


def by_number():
    """Each number from 0 with its call, or None when it is reserved."""
    calls = {c["number"]: c for c in api.CALLS}
    return [(n, calls.get(n)) for n in range(count())]


def write(path, lines):
    with open(path, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")


def api_inc():
    major, minor, patch = api.VERSION
    lines = ["; " + HEADER, "",
             '.define VERSION_TEXT "%d.%d.%d"' % api.VERSION,
             "VERSION_MAJOR = %d" % major,
             "VERSION_MINOR = %d" % minor,
             "VERSION_PATCH = %d" % patch, "",
             "GATE_ENTRIES          = $%04X" % api.GATE_ENTRIES, ""]
    for c in api.CALLS:
        lines.append("CALL_%-16s = %d" % (c["name"].upper(), c["number"]))
    lines.append("CALL_COUNT %s = %d" % (" " * 11, count()))
    lines.append("")
    for c in api.CALLS:
        lines.append("API_%-17s = GATE_ENTRIES + 3 * CALL_%s" % (c["name"].upper(),
                                                              c["name"].upper()))
    lines.append("")
    for number, name, message in api.ERRORS:
        lines.append("ERR_%-18s = %d" % (name, number))
    lines.append("")
    for start, size, name, field in api.FIND_BUFFER:
        if name:
            lines.append("FIND_%-17s = %d" % (name, start))
    last = api.FIND_BUFFER[-1]
    lines.append("FIND_BUFFER_SIZE      = %d" % (last[0] + last[1]))
    return lines


def api_s():
    lines = ["; " + HEADER, "",
             '.include "api.inc"', "",
             ".export api_table, api_bad, errmsg_table"]
    written = ["api_" + c["name"] for c in api.CALLS if c["written"]]
    if written:
        lines.append(".import " + ", ".join(written))
    lines += ["", '.segment "CODE"', "",
              "; api_table: for each call by number, the address of its routine and the ROM bank",
              "; that holds it.",
              "api_table:"]
    for number, c in by_number():
        routine = "api_" + c["name"] if c and c["written"] else "api_bad"
        lines.append("        .word %-16s; %d %s" % (routine, number, c["name"] if c else "reserved"))
        lines.append("        .byte <.bank(%s)" % routine)
    lines += ["",
              "; api_bad: the routine of a call the kernel lacks. Returns carry set, A = 1.",
              "api_bad:",
              "        lda #ERR_BAD_FUNCTION",
              "        sec",
              "        rts", "",
              "; errmsg_table: for each error its number, the length of its message, and the",
              "; message. A 0 ends the table.",
              "errmsg_table:"]
    for number, name, message in api.ERRORS:
        lines.append('        .byte ERR_%s, %d, "%s"' % (name, len(message), message))
    lines.append("        .byte 0")
    return lines


def registers(pairs):
    if not pairs:
        return "none"
    return "<br>".join("`%s` %s" % (register, meaning) for register, meaning in pairs)


def api_md():
    lines = ["# UXDOS16 API", "", "<!-- %s -->" % HEADER, "",
             "Version %d.%d.%d." % api.VERSION, "",
             "Conventions:", ""]
    lines += [line.strip() for line in api.__doc__.split("Conventions for every call:")[1]
              .strip().replace("\n  ", " ").split("\n")]
    lines += ["", "## Calls", "",
              "| Call | Number | Entry | MS-DOS | In | Out | Errors | Written |",
              "|---|---|---|---|---|---|---|---|"]
    for number, c in by_number():
        if c is None:
            lines.append("| reserved | %d | `$%04X` | none | none | none | 1 | no |" % (
                number, api.GATE_ENTRIES + 3 * number))
            continue
        msdos = "%02Xh" % c["msdos"] if c["msdos"] is not None else "none"
        errors = ", ".join(str(n) for n in c["errors"]) or "none"
        lines.append("| `%s` | %d | `$%04X` | %s | %s | %s | %s | %s |" % (
            c["name"], c["number"], api.GATE_ENTRIES + 3 * c["number"], msdos,
            registers(c["in_"]), registers(c["out"]), errors, "yes" if c["written"] else "no"))
    lines += ["", "## What each call does", ""]
    for number, c in by_number():
        if c is None:
            lines.append("- %d, reserved: %s" % (number, api.RESERVED[number]))
        else:
            lines.append("- `%s`: %s" % (c["name"], c["does"]))
    lines += ["", "## Errors", "", "| Number | Asm name | Message |", "|---|---|---|"]
    for number, name, message in api.ERRORS:
        lines.append("| %d | `ERR_%s` | %s |" % (number, name, message))
    lines += ["", "## Find buffer", "", "| Offset | Size | Field |", "|---|---|---|"]
    for offset, size, name, field in api.FIND_BUFFER:
        lines.append("| %d | %d | %s |" % (offset, size, field))
    return lines


def uxi_block():
    """The API_ CONST lines for DOS.UXI, packed to UXI_WIDTH columns."""
    lines, line = [], ""
    for c in api.CALLS:
        item = "API_%s AS UWORD = $%04X" % (c["name"].upper(), api.GATE_ENTRIES + 3 * c["number"])
        if line and len(line) + 2 + len(item) <= UXI_WIDTH:
            line += ", " + item
        else:
            if line:
                lines.append(line)
            line = "  CONST " + item
    lines.append(line)
    return lines


def update_dos_uxi():
    """Replace the block between UXI_BEGIN and UXI_END in DOS.UXI. Return a fault or None."""
    with open(DOS_UXI, encoding="utf-8", newline="") as source:
        text = source.read()
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.split(newline)
    if lines.count(UXI_BEGIN) != 1 or lines.count(UXI_END) != 1:
        return "lib/DOS.UXI needs one line each of UXI_BEGIN and UXI_END"
    begin, end = lines.index(UXI_BEGIN), lines.index(UXI_END)
    if end < begin:
        return "lib/DOS.UXI has UXI_END before UXI_BEGIN"
    updated = newline.join(lines[:begin + 1] + uxi_block() + lines[end:])
    if updated != text:
        with open(DOS_UXI, "w", encoding="utf-8", newline="") as out:
            out.write(updated)
    return None


def main():
    faults = check()
    if faults:
        for fault in faults:
            print("genapi: " + fault)
        sys.exit(1)
    os.makedirs(GEN, exist_ok=True)
    write(os.path.join(GEN, "api.inc"), api_inc())
    write(os.path.join(GEN, "api.s"), api_s())
    write(os.path.join(ROOT, "docs", "API.md"), api_md())
    fault = update_dos_uxi()
    if fault:
        print("genapi: " + fault)
        sys.exit(1)


if __name__ == "__main__":
    main()
